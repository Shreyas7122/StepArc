// Load custom foods from localStorage on initialization
if (typeof window !== 'undefined' && window.localStorage) {
  try {
    const saved = localStorage.getItem('steparc_custom_foods');
    if (saved) {
      const custom = JSON.parse(saved);
      custom.forEach(item => {
        if (!foodDatabase.some(f => f.id === item.id)) {
          foodDatabase.push(item);
        }
      });
    }
  } catch (e) {
    console.error('Failed to load custom foods:', e);
  }
}

export function saveCustomFood(food) {
  foodDatabase.push(food);
  if (typeof window !== 'undefined' && window.localStorage) {
    try {
      const saved = localStorage.getItem('steparc_custom_foods');
      const custom = saved ? JSON.parse(saved) : [];
      custom.push(food);
      localStorage.setItem('steparc_custom_foods', JSON.stringify(custom));
      // Dispatch custom event to notify components of database changes
      window.dispatchEvent(new CustomEvent('food-database-updated'));
    } catch (e) {
      console.error('Failed to save custom food:', e);
    }
  }
}


